/* ============================================================================
   Shared table + section primitives
   Use these across every export to get consistent grid layout and safe
   pagination. `Section` puts its title on a fresh page after the first one.
   `Table` renders a header + row grid using flex weights per column.
   ============================================================================ */

export type TableColumn<T> = {
  header: string;
  /** Flex weight for the column (relative). Defaults to 1. */
  flex?: number;
  /** Cell renderer. Return a string, number, or a react-pdf primitive. */
  cell: (row: T, index: number) => import("react").ReactNode;
  /** Optional alignment. */
  align?: "left" | "right" | "center";
  /** Monospace-friendly (used for numeric columns). */
  mono?: boolean;
};

/** A row that spans every column, drawn as a full-width category header band. */
export type TableGroupRow = { __group: true; label: string; meta?: string };
/** A data row (any shape). */
export type TableDataRow<T> = { __group?: false } & T;
export type TableRow<T> = TableGroupRow | TableDataRow<T>;

const ZEBRA_BG = "#f7f8fa";
const HEADER_BG = "#f1f2f4";
const GROUP_BG = "#eef1f6";
const BORDER = "#d8dbe0";

const tableStyles = StyleSheet.create({
  // NOTE: no borderRadius / borderWidth on the wrap — react-pdf's border-clip
  // math overflows (`unsupported number: -9.7e+21` in clipBorderTop) when a
  // bordered+rounded container is split across pages with wrap={false} rows.
  // Borders live on the rows themselves.
  wrap: { marginBottom: 8 },
  th: {
    flexDirection: "row",
    backgroundColor: HEADER_BG,
    borderTopWidth: 0.5,
    borderTopColor: BORDER,
    borderBottomWidth: 0.75,
    borderBottomColor: DARK,
    paddingVertical: 5,
    paddingHorizontal: 6,
    fontSize: 8.5,
    fontWeight: 700,
    color: DARK,
    textTransform: "uppercase",
    letterSpacing: 0.4,
  },
  tr: {
    flexDirection: "row",
    borderBottomWidth: 0.25,
    borderBottomColor: BORDER,
    paddingVertical: 4,
    paddingHorizontal: 6,
    fontSize: 10,
    color: DARK,
  },
  trZebra: { backgroundColor: ZEBRA_BG },
  groupRow: {
    flexDirection: "row",
    justifyContent: "space-between",
    alignItems: "center",
    backgroundColor: GROUP_BG,
    borderTopWidth: 0.5,
    borderTopColor: BORDER,
    borderBottomWidth: 0.5,
    borderBottomColor: BORDER,
    paddingVertical: 4,
    paddingHorizontal: 6,
  },
  groupLabel: { fontSize: 10, fontWeight: 700, color: DARK, textTransform: "uppercase", letterSpacing: 0.5 },
  groupMeta: { fontSize: 9, color: GRAY },
  cellText: { fontSize: 10, color: DARK },
  cellMono: { fontSize: 10, color: DARK, fontFamily: "OpenSans" },
});

function isGroup<T>(r: TableRow<T>): r is TableGroupRow {
  return (r as TableGroupRow).__group === true;
}

export function Table<T>({
  columns,
  rows,
  emptyLabel = "No data",
  zebra = true,
}: {
  columns: TableColumn<T>[];
  rows: TableRow<T>[];
  emptyLabel?: string;
  zebra?: boolean;
}) {
  if (rows.length === 0) {
    return <Text style={{ fontSize: 10, color: GRAY }}>{emptyLabel}</Text>;
  }
  let dataIdx = -1;
  return (
    <View style={tableStyles.wrap}>
      <View style={tableStyles.th}>
{/* NOTE: `fixed` cannot be used on nested Views — it only works on direct
    children of Page. Applying it here caused clipBorderTop to receive
    massively negative coords and threw `unsupported number` at render. */}
        {columns.map((col, i) => (
          <Text
            key={i}
            style={{
              flex: col.flex ?? 1,
              textAlign: col.align ?? "left",
              paddingRight: 6,
            }}
          >
            {N(col.header)}
          </Text>
        ))}
      </View>
      {rows.map((row, ri) => {
        if (isGroup(row)) {
          return (
            <View key={ri} style={tableStyles.groupRow} wrap={false}>
              <Text style={tableStyles.groupLabel}>{N(row.label)}</Text>
              {row.meta ? <Text style={tableStyles.groupMeta}>{N(row.meta)}</Text> : null}
            </View>
          );
        }

        dataIdx += 1;
        const striped = zebra && dataIdx % 2 === 1;
        return (
          <View
            key={ri}
            style={[tableStyles.tr, striped ? tableStyles.trZebra : null] as any}
            wrap={false}
          >
            {columns.map((col, ci) => {
              const raw = col.cell(row as TableDataRow<T>, dataIdx);
              const node =
                typeof raw === "string" || typeof raw === "number" ? (
                  <Text style={col.mono ? tableStyles.cellMono : tableStyles.cellText}>
                    {N(String(raw))}
                  </Text>
                ) : (
                  raw
                );
              return (
                <View
                  key={ci}
                  style={{
                    flex: col.flex ?? 1,
                    paddingRight: 6,
                    alignItems:
                      col.align === "right"
                        ? "flex-end"
                        : col.align === "center"
                          ? "center"
                          : "flex-start",
                  }}
                >
                  {node}
                </View>
              );
            })}
          </View>
        );
      })}
    </View>
  );
}


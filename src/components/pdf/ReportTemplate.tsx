export interface ReportTemplateProps {
  festivalName: string;
  festivalDates: string;
  reportTitle: string;
  reportSubtitle?: string;
  accentColor: AccentKey;
  generatedAt?: Date;
  summary?: ReactNode;
  children: ReactNode;
}

const fmtCoverDate = (d: Date) =>
  d.toLocaleDateString("en-GB", { day: "numeric", month: "long", year: "numeric" });

export function ReportTemplate({
  festivalName,
  festivalDates,
  reportTitle,
  reportSubtitle,
  accentColor,
  generatedAt,
  summary,
  children,
}: ReportTemplateProps) {
  const accent = ACCENT[accentColor];
  const gen = generatedAt ?? new Date();
  return (
    <Document title={`${festivalName} — ${reportTitle}`} author="Full Event Project">
      <Page size="A4" style={s.page}>
        {/* Header (page 1 prominent; on subsequent pages the same layout repeats only via new Pages) */}
        <Text style={[s.festivalName, { color: accent.fg }]}>{N(festivalName)}</Text>
        <Text style={s.festivalDates}>{N(festivalDates)}</Text>

        <View style={s.headerRow}>
          <View style={[s.accentDot, { backgroundColor: accent.fg }]} />
          <Text style={s.reportTitle}>{N(reportTitle)}</Text>
        </View>
        {reportSubtitle ? <Text style={s.subtitle}>{N(reportSubtitle)}</Text> : null}
        <View style={s.divider} />

        {summary ? <View style={s.summaryBox}>{summary}</View> : null}

        {children}

        <View style={s.footer} fixed>
          <Text style={s.footerLeft}>{N(festivalName)}</Text>
          <Text style={s.footerCenter}>{N(reportTitle)}</Text>
          <Text style={s.footerRight} render={({ pageNumber, totalPages }) => `Page ${pageNumber} / ${totalPages}`} />
        </View>
        <Text style={s.footerCredit} fixed>
          {N(`Generated by Full Event Project · ${fmtCoverDate(gen)}`)}
        </Text>
      </Page>
    </Document>
  );
}


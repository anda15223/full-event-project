export const fmtFilename = (slug: string, section: string, d?: Date) => {
  const dt = d ?? new Date();
  const y = dt.getFullYear();
  const m = String(dt.getMonth() + 1).padStart(2, "0");
  const day = String(dt.getDate()).padStart(2, "0");
  return `${slug}-${section}-${y}${m}${day}.pdf`;
};
